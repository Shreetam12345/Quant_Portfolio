-- Flag price outliers using IQR method
CREATE OR REPLACE FUNCTION flag_outliers(p_symbol VARCHAR, p_window INT DEFAULT 20)
RETURNS INT AS $$
DECLARE
    updated_count INT;
BEGIN
    WITH stats AS (
        SELECT
            id,
            log_return,
            PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY log_return)
                OVER (PARTITION BY symbol ORDER BY ts ROWS BETWEEN p_window PRECEDING AND CURRENT ROW) AS q1,
            PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY log_return)
                OVER (PARTITION BY symbol ORDER BY ts ROWS BETWEEN p_window PRECEDING AND CURRENT ROW) AS q3
        FROM prices_clean
        WHERE symbol = p_symbol
    ),
    iqr_bounds AS (
        SELECT id,
               log_return,
               q1 - 1.5*(q3-q1) AS lower_bound,
               q3 + 1.5*(q3-q1) AS upper_bound
        FROM stats
    )
    UPDATE prices_clean pc
    SET is_outlier = TRUE
    FROM iqr_bounds ib
    WHERE pc.id = ib.id
      AND (pc.log_return < ib.lower_bound OR pc.log_return > ib.upper_bound);

    GET DIAGNOSTICS updated_count = ROW_COUNT;
    RETURN updated_count;
END;
$$ LANGUAGE plpgsql;

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_prices_symbol_ts ON prices_clean(symbol, ts DESC);
CREATE INDEX IF NOT EXISTS idx_signals_pair_ts ON signals(pair_id, ts DESC);
CREATE INDEX IF NOT EXISTS idx_raw_symbol_ts ON raw_ohlcv(symbol, ts DESC);
